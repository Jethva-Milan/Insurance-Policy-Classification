from sklearn.metrics import confusion_matrix

"""Load Dataset"""

df = pd.read_csv("insurance_40000_clean.csv")

df.head()

"""Basic Dataset Checking"""

print("Shape:", df.shape)

print("\nColumns:")
print(df.columns)

print("\nDataset Information:")
df.info()

print("\nNull Values:")
print(df.isnull().sum())

print("\nDuplicate Rows:")
print(df.duplicated().sum())

"""──────── DATA PREPROCESSING ────────

Remove Duplicate Rows
"""

df = df.drop_duplicates()

print("Shape after removing duplicates:", df.shape)

"""Target Distribution"""

plt.figure(figsize=(7, 5))

sns.countplot(data=df, x="Insurance_Taken")

plt.title("Insurance Taken Distribution")
plt.xlabel("Insurance Taken")
plt.ylabel("Count")

plt.show()

"""Remove Data Leakage Column"""

df = df.drop(columns=["Policy_Status"])

"""Separate Features and Target"""

X = df.drop("Insurance_Taken", axis=1)

y = df["Insurance_Taken"]

columns_before_removing = df.columns.tolist()
print("Columns Before Removing:")
print(columns_before_removing)

# Remove Policy_Status if it exists
if "Policy_Status" in df.columns:
    df = df.drop(columns=["Policy_Status"])

# After removing
print("\nColumns After Removing:")
print(df.columns.tolist())

# See dataset shape
print("\nDataset Shape After Removing:")
print(df.shape)

# Display first 5 rows
print("\nFirst 5 Rows:")
print(df.head())

print("Features (X):")
print(X.head())

print("\nTarget (y):")
print(y.head())

print("\nX Shape:", X.shape)
print("y Shape:", y.shape)

"""Encode All Categorical Columns"""

label_encoder = LabelEncoder()

categorical_columns = X.select_dtypes(include="object").columns

for column in categorical_columns:
    X[column] = label_encoder.fit_transform(X[column])

y = LabelEncoder().fit_transform(y)

"""Encode All Categorical Columns Prints"""

print(X.head())

print("\nEncoded Target:")
print(pd.Series(y).value_counts())

"""Train-Test Split"""

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Data:", X_train.shape)
print("Testing Data:", X_test.shape)

"""──────── MODEL TRAINING **────────**

Feature Scaling  in algorithm

*   Logistic Regression
*   KNN
*   SVM
*   Naive Byes
"""

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)

X_test_scaled = scaler.transform(X_test)

"""Algorithm 1: Logistic Regression"""

logistic_model = LogisticRegression(max_iter=5000)

logistic_model.fit(X_train_scaled, y_train)

y_pred_logistic = logistic_model.predict(X_test_scaled)

"""Evalution"""

print("Accuracy:",
      accuracy_score(y_test, y_pred_logistic))

print("Precision:",
      precision_score(y_test, y_pred_logistic, pos_label=1))

print("Recall:",
      recall_score(y_test, y_pred_logistic, pos_label=1))

print("F1 Score:",
      f1_score(y_test, y_pred_logistic, pos_label=1))

print("\nClassification Report:\n")

print(classification_report(
    y_test,
    y_pred_logistic,
    target_names=['No', 'Yes']
))

"""Confusion Matrix"""

cm = confusion_matrix(y_test, y_pred_logistic)

plt.figure(figsize=(6, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d"
)

plt.title("Logistic Regression Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")

plt.show()

"""Algorithm 2: Decision Tree"""

